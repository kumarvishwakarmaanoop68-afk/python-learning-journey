# Day 3 practice questions

# 1. Print every item from a list.
fruits = ["apple", "banana", "mango", "orange"]
for fruit in fruits:
    print(fruit)

# 2. Find the largest number in a list.
numbers = [12, 45, 7, 89, 23]
print("Largest:", max(numbers))

# 3. Remove duplicates using a set.
values = [1, 2, 2, 3, 4, 4, 5]
print("Unique values:", set(values))

# 4. Access a value from a dictionary.
student = {"name": "Anoop", "course": "Diploma IT"}
print("Course:", student["course"])
